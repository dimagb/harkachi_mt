@router.get("/factors", summary="Внешние источники данных")
def factors() -> dict:
    by_status: dict = {}
    for source in EXTERNAL_SOURCES:
        by_status[source["status"]] = by_status.get(source["status"], 0) + 1
    return {
        "sources": EXTERNAL_SOURCES,
        "count": len(EXTERNAL_SOURCES),
        "by_status": by_status,
        "note": (
            "confirmed — эффект измерен; measured_not_applied — эффект "
            "измерен, но в сданной версии прогноза не применён; stub — "
            "заготовка, эффект не измерен, источник не заявляется. Данные "
            "кешируются локально: сервис не ходит в сеть во время работы."
        ),
    }


